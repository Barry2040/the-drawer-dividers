#!/usr/bin/env python3
"""Build the distributable files.

  dist/makerworld/en/*.scad   single-file versions (library inlined) for MakerWorld
  dist/makerworld/de/*.scad   the same with German Customizer names
  designer/scad_lib.js        library embedded into the designer for the job export

Run from anywhere:  python tools/build.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCAD = ROOT / "scad"
LIB = SCAD / "lib" / "drawer_divider.scad"
ENTRIES = ["connector.scad", "wall.scad", "rail.scad", "tolerance_test.scad"]

from i18n_de import FILES as DE_FILES, SECTIONS as DE_SECTIONS, VARS as DE_VARS, LABELS as DE_LABELS  # noqa: E402

USE_RE = re.compile(r"^\s*use\s*<lib/drawer_divider\.scad>\s*$")
SECTION_RE = re.compile(r"^/\*\s*\[(.+?)\]\s*\*/\s*$")
VAR_RE = re.compile(r"^(\w+)(\s*=\s*)(.+?);(\s*//\s*\[(.*)\])?\s*$")


def library_body() -> str:
    return LIB.read_text(encoding="utf-8").strip() + "\n"


def inline(src: str, translate: bool) -> str:
    out, aliases, pending_desc = [], [], None
    hidden = False
    for line in src.splitlines():
        if USE_RE.match(line):
            continue
        m = SECTION_RE.match(line)
        if m:
            if pending_desc is not None:
                out.append(pending_desc)
                pending_desc = None
            name = m.group(1)
            if name == "Hidden":
                hidden = True
                out.append(line)
                out.extend(aliases)
                continue
            out.append(f"/* [{DE_SECTIONS.get(name, name) if translate else name}] */")
            continue
        if not hidden and line.startswith("//") and not line.startswith("// ["):
            if pending_desc is not None:
                out.append(pending_desc)
            pending_desc = line
            continue
        v = VAR_RE.match(line) if not hidden else None
        if v and translate and v.group(1) in DE_VARS:
            en = v.group(1)
            de_name, de_desc = DE_VARS[en]
            if pending_desc is not None:
                out.append(f"// {de_desc}" if de_desc else pending_desc)
                pending_desc = None
            opts = v.group(5)
            tail = f" // [{translate_options(opts)}]" if opts is not None else ""
            out.append(f"{de_name}{v.group(2)}{v.group(3)};{tail}")
            aliases.append(f"{en} = {de_name};")
            continue
        if pending_desc is not None:
            out.append(pending_desc)
            pending_desc = None
        out.append(line)
    text = "\n".join(out).rstrip() + "\n"
    banner = ("\n// " + "=" * 76 + "\n//  Library (scad/lib/drawer_divider.scad, inlined by tools/build.py)\n// "
              + "=" * 76 + "\n")
    return text + banner + library_body()


def translate_options(opts: str) -> str:
    # only "value:Label" lists carry text; ranges like 1:1:40 stay as they are
    parts = [p.strip() for p in opts.split(",")]
    if not all(":" in p for p in parts) or re.fullmatch(r"[-\d.]+(:[-\d.]+){1,2}", opts.strip()):
        return opts
    res = []
    for p in parts:
        value, label = p.split(":", 1)
        res.append(f"{value}:{DE_LABELS.get(value.strip(), label)}")
    return ", ".join(res)


def main():
    for lang in ("en", "de"):
        out_dir = ROOT / "dist" / "makerworld" / lang
        out_dir.mkdir(parents=True, exist_ok=True)
        for name in ENTRIES:
            src = (SCAD / name).read_text(encoding="utf-8")
            target = DE_FILES.get(name, name) if lang == "de" else name
            text = inline(src, translate=(lang == "de"))
            if lang == "de":
                text = "// Deutsche Version – automatisch erzeugt aus scad/" + name + "\n" + text
            (out_dir / target).write_text(text, encoding="utf-8")
            print(f"  dist/makerworld/{lang}/{target}")

    js = ("// Generated by tools/build.py from scad/lib/drawer_divider.scad – do not edit.\n"
          f"window.DD_SCAD_LIB = {json.dumps(library_body(), ensure_ascii=False)};\n")
    (ROOT / "designer" / "scad_lib.js").write_text(js, encoding="utf-8")
    print("  designer/scad_lib.js")


if __name__ == "__main__":
    main()
